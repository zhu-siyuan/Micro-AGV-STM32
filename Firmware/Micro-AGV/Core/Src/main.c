// 串口接收中断回调函数
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1) // 确认是蓝牙发来的
    {
        uint8_t received_byte = rx_buffer[0];

        // 简单的状态机解析 (记得我们定的帧头是 0xA5 吗？)
        switch (rx_state)
        {
            case STATE_WAIT_HEADER:
                if (received_byte == 0xA5) // 收到帧头
                {
                    data_index = 0;
                    data_buffer[data_index++] = received_byte;
                    rx_state = STATE_RECEIVE_BODY;
                }
                break;

            case STATE_RECEIVE_BODY:
                data_buffer[data_index++] = received_byte;
                
                // 假设我们的协议长度是 8 个字节 (根据你的定义修改)
                if (data_index >= 8) 
                {
                    // 收满了，处理数据！
                    // TODO: 在这里解析 X, Y, Speed，然后调用 Set_Motor_Speed
                    
                    // 比如简单的测试：如果第2个字节是 0x01，就前进
                    if (data_buffer[1] == 0x01) Set_Motor_Speed(500, 500);
                    else if (data_buffer[1] == 0x02) Set_Motor_Speed(0, 0);

                    // 恢复状态，等下一包
                    rx_state = STATE_WAIT_HEADER;
                }
                break;
        }

        // 重新开启接收中断 (这一句千万不能少！否则收一次就聋了)
        HAL_UART_Receive_IT(&huart1, rx_buffer, 1);
    }
}
